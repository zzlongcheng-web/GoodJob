import assert from "node:assert/strict";
import { newIntakeToken, intakeTokenDigest, intakeGrantValid, intakeDuplicateReasons } from "./external-customer-intake-policy.js";
import { deniedAgentApiReason } from "./agent-api-policy.js";
const now = Date.now();
const actor = {id:"a",teamId:"t1",status:"active",authVersion:2};
const grant = {ownerId:"a",teamId:"t1",authVersion:2,expiresAt:now+1000,revokedAt:null};
const token = newIntakeToken();
assert.match(token,/^gj_intake_[A-Za-z0-9_-]{43}$/);
assert.match(intakeTokenDigest(token)!,/^[a-f0-9]{64}$/);
assert.notEqual(token,newIntakeToken());
assert.equal(intakeTokenDigest("runner-token"),null);
assert.equal(intakeTokenDigest("a.b.c"),null);
assert.equal(intakeGrantValid(grant,actor,now),true);
assert.equal(intakeGrantValid({...grant,expiresAt:now},actor,now),false);
assert.equal(intakeGrantValid({...grant,revokedAt:now},actor,now),false);
assert.equal(intakeGrantValid(grant,{...actor,teamId:"t2"},now),false);
assert.equal(intakeGrantValid(grant,{...actor,id:"b"},now),false);
assert.equal(intakeGrantValid(grant,{...actor,status:"disabled"},now),false);
assert.equal(intakeGrantValid(grant,{...actor,authVersion:3},now),false);
assert.equal(intakeGrantValid(grant,{...actor,expiresAt:new Date(now).toISOString()},now),false);
const rows = [{company:"Alpha Machine",companyFullName:"Alpha Machine LLC",country:"美国",email:"sales@example.test",phone:"+1 (713) 555-0100",teamId:"t1"}];
assert.ok(intakeDuplicateReasons({company:" alpha  machine ",country:"美国"},rows,"t1").includes("company_country"));
assert.ok(intakeDuplicateReasons({company:"Other",companyFullName:"ALPHA MACHINE LLC",country:"美国"},rows,"t1").includes("full_name_country"));
assert.ok(intakeDuplicateReasons({company:"Other",country:"美国",email:"Sales@EXAMPLE.TEST"},rows,"t1").includes("email"));
assert.ok(intakeDuplicateReasons({company:"Other",country:"美国",whatsapp:"+17135550100"},rows,"t1").includes("telephone"));
assert.deepEqual(intakeDuplicateReasons({company:"Alpha Machine",country:"美国",email:"sales@example.test"},rows,"t2"),[]);
assert.deepEqual(intakeDuplicateReasons({company:"Other",country:"美国",phone:"123"},rows,"t1"),[]);
assert.deepEqual(intakeDuplicateReasons({company:"Alpha Machine",country:"加拿大"},rows,"t1"),[]);
assert.ok(deniedAgentApiReason("/api/external-customer-intake/tokens"));
console.log("external customer intake policy tests passed");
